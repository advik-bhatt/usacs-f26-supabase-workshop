// Pulls real near-Earth asteroids from NASA/JPL and writes supabase/seed.sql.
//
//   npm run nasa:fetch
//
// Two public APIs, no key needed:
//   Close Approach Data (CAD): which asteroids pass near Earth in the next
//     ten years, when, how close, and how fast.
//   Small-Body Database (SBDB): each one's orbit and size.
//
// The output is committed so the workshop works offline. Re-run it to refresh.

import { writeFileSync } from "node:fs";

const CAD = "https://ssd-api.jpl.nasa.gov/cad.api";
const SBDB = "https://ssd-api.jpl.nasa.gov/sbdb.api";
const HOW_MANY = Number(process.argv[2] ?? 60);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const cadUrl = `${CAD}?date-min=now&date-max=%2B3650&dist-max=0.05&h-max=26&fullname=true&sort=date`;
const cad = await (await fetch(cadUrl)).json();
const col = Object.fromEntries(cad.fields.map((f, i) => [f, i]));
const rows = cad.data.map((r) => ({
  des: r[col.des],
  name: r[col.fullname].trim(),
  ca_jd: Number(r[col.jd]),
  ca_date: r[col.cd],
  ca_dist_au: Number(r[col.dist]),
  v_inf_kms: Number(r[col.v_inf]),
  h: Number(r[col.h]),
}));
console.log(`CAD: ${rows.length} close approaches within 0.05 AU in the next 10 years`);

// One row per asteroid (its first approach), then a spread: the biggest ones
// plus a sample across the decade so there's always something coming soon.
const firstPass = [...new Map(rows.map((r) => [r.des, r])).values()];
const biggest = [...firstPass].sort((a, b) => a.h - b.h).slice(0, Math.ceil(HOW_MANY / 3));
const rest = firstPass.filter((r) => !biggest.includes(r));
const stride = Math.max(1, Math.floor(rest.length / (HOW_MANY - biggest.length)));
// and always the famous one: Apophis passes inside the orbit of our GPS
// satellites on April 13, 2029
const famous = firstPass.filter((r) => ["99942"].includes(r.des));
const picked = [...new Set([...famous, ...biggest, ...rest.filter((_, i) => i % stride === 0)])].slice(0, HOW_MANY);

const out = [];
for (const r of picked) {
  const res = await fetch(`${SBDB}?sstr=${encodeURIComponent(r.des)}&full-prec=true&phys-par=true`);
  if (!res.ok) {
    console.warn(`skip ${r.des}: SBDB ${res.status}`);
    continue;
  }
  const body = await res.json();
  const el = Object.fromEntries(body.orbit.elements.map((e) => [e.name, Number(e.value)]));
  const phys = Object.fromEntries((body.phys_par ?? []).map((p) => [p.name, Number(p.value)]));
  out.push({
    ...r,
    epoch: Number(body.orbit.epoch),
    a: el.a, e: el.e, i: el.i, om: el.om, w: el.w, ma: el.ma,
    // measured diameter when JPL has one, otherwise estimate from brightness
    diameter_km: phys.diameter || (1329 / Math.sqrt(0.14)) * 10 ** (-r.h / 5),
    diameter_measured: Boolean(phys.diameter),
    pha: Boolean(body.object.pha),
  });
  process.stdout.write(".");
  await sleep(150); // be polite
}
console.log(`\nSBDB: ${out.length} orbits`);

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const lines = out.map((o) =>
  `  (${[q(o.des), q(o.name), o.ca_jd, q(o.ca_date), o.ca_dist_au, o.v_inf_kms, o.h, o.diameter_km.toFixed(4),
    o.diameter_measured, o.pha, o.epoch, o.a, o.e, o.i, o.om, o.w, o.ma].join(", ")})`,
);

writeFileSync("supabase/seed.sql", `-- Generated by \`npm run nasa:fetch\` on ${new Date().toISOString().slice(0, 10)}.
-- Runs after the migrations on the first \`supabase start\` and every \`supabase db reset\`.
-- Source: NASA/JPL Small-Body Database and Close Approach Data APIs (ssd-api.jpl.nasa.gov).
-- Real orbits; the "headed for Earth" part is the drill.

insert into public.asteroids
  (des, name, ca_jd, ca_date, ca_dist_au, v_inf_kms, h, diameter_km,
   diameter_measured, pha, epoch, a, e, i, om, w, ma)
values
${lines.join(",\n")}
on conflict (des) do update set
  ca_jd = excluded.ca_jd, ca_date = excluded.ca_date, ca_dist_au = excluded.ca_dist_au,
  v_inf_kms = excluded.v_inf_kms, h = excluded.h, diameter_km = excluded.diameter_km,
  diameter_measured = excluded.diameter_measured, pha = excluded.pha, epoch = excluded.epoch,
  a = excluded.a, e = excluded.e, i = excluded.i, om = excluded.om, w = excluded.w, ma = excluded.ma;
`);
console.log("wrote supabase/seed.sql");
